// Generates the Svelte 5 port from the Custom Elements Manifest of @intuition-ui/core.
//
//   src/generated/<Name>.svelte  one component per custom element (Button.svelte)
//   src/index.generated.ts       exports
//
// Props come from the manifest attributes (type and default); events become
// `on<event-name>` props (oniu-press). `--check` fails if committed files are out of date.
// INTUITION_MANIFEST overrides the manifest path (used to test the generator).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const manifestPath =
  process.env.INTUITION_MANIFEST ??
  require.resolve('@intuition-ui/core/custom-elements.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const check = process.argv.includes('--check');

const elements = manifest.modules.flatMap((m) =>
  (m.declarations ?? []).filter((d) => d.customElement && d.tagName),
);

const quote = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`);
const jsdoc = (text, indent) =>
  text
    ? `${indent}/** ${text.replace(/\*\//g, '* /').replace(/\n/g, ' ')} */\n`
    : '';
const eventDetail = (e) =>
  e.type?.text?.match(/^CustomEvent<(.+)>$/)?.[1] ?? 'unknown';
const componentName = (className) => className.replace(/^Iu/, ''); // IuButton -> Button

const header = (
  cmd,
) => `Generated by scripts/generate.mjs from @intuition-ui/core/custom-elements.json.
  Do not edit by hand: run \`${cmd}\`.`;

function component(el) {
  const members = (el.members ?? []).filter(
    (m) => m.kind === 'field' && m.attribute && !m.static && !m.readonly,
  );
  const events = el.events ?? [];
  const propTypes = [
    ...members.map(
      (m) =>
        `${jsdoc(m.description, '    ')}    ${quote(m.name)}?: ${m.type?.text ?? 'unknown'};`,
    ),
    ...events.map(
      (e) =>
        `${jsdoc(e.description, '    ')}    ${quote(`on${e.name}`)}?: (event: CustomEvent<${eventDetail(e)}>) => void;`,
    ),
    '    children?: Snippet;',
  ];
  const destructure = members.map((m) =>
    m.default ? `${m.name} = ${m.default}` : m.name,
  );
  const bindings = members.map((m) => `{${m.name}}`).join(' ');
  return `<!--
  ${header('npm run generate -w @intuition-ui/svelte')}
-->
<script lang="ts">
  import '@intuition-ui/core';
  import type { Snippet } from 'svelte';
  import type { HTMLAttributes } from 'svelte/elements';

${jsdoc(el.summary ?? el.description, '  ')}  interface Props extends Omit<HTMLAttributes<HTMLElement>, ${members.map((m) => `'${m.name}'`).join(' | ') || 'never'}> {
${propTypes.join('\n')}
  }

  let { ${[...destructure, 'children', '...rest'].join(', ')} }: Props = $props();
</script>

<!-- The custom element is interactive; the compiler cannot know it. -->
<!-- svelte-ignore a11y_no_static_element_interactions, a11y_click_events_have_key_events -->
<${el.tagName} ${bindings} {...rest}>{@render children?.()}</${el.tagName}>
`;
}

const outputs = {};
for (const el of elements) {
  outputs[`src/generated/${componentName(el.name)}.svelte`] = component(el);
}
outputs['src/index.generated.ts'] =
  `// ${header('npm run generate -w @intuition-ui/svelte').replace('\n  ', '\n// ')}
${elements
  .map(
    (el) =>
      `export { default as ${componentName(el.name)} } from './generated/${componentName(el.name)}.svelte';`,
  )
  .join('\n')}
`;

let stale = false;
if (check) {
  const expected = new Set(Object.keys(outputs));
  let existing = [];
  try {
    existing = readdirSync('src/generated').map((f) => `src/generated/${f}`);
  } catch {}
  for (const f of existing) if (!expected.has(f)) stale = true;
  for (const [file, content] of Object.entries(outputs)) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== content) stale = true;
  }
  if (stale) {
    console.error(
      'Svelte port is out of date. Run `npm run generate -w @intuition-ui/svelte`.',
    );
    process.exit(1);
  }
  console.log('Svelte port is up to date.');
} else {
  mkdirSync('src/generated', { recursive: true });
  for (const [file, content] of Object.entries(outputs))
    writeFileSync(file, content);
  console.log(
    `Generated ${Object.keys(outputs).length} file(s) (${elements.length} element(s)).`,
  );
}
