// Generates the Vue port from the Custom Elements Manifest of @intuition-ui/core.
//
//   src/components.generated.ts  Vue components (IuButton) that render the custom element
//
// Exported as IuButton (a valid JS identifier) and used in templates in kebab-case,
// <iu-button>, which the Vue style guide accepts. Vue resolves the tag to the imported
// component, so consumers must not mark iu-* as custom elements (isCustomElement).
//
// Props come from the manifest attributes (type, default, allowed values),
// events become declared emits. `--check` fails if the committed file is out of date.
// INTUITION_MANIFEST overrides the manifest path (used to test the generator).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const manifestPath =
  process.env.INTUITION_MANIFEST ??
  require.resolve('@intuition-ui/core/custom-elements.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const check = process.argv.includes('--check');

const elements = manifest.modules.flatMap((m) =>
  (m.declarations ?? []).filter((d) => d.customElement && d.tagName),
);

const quote = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`);
const jsdoc = (text, indent) =>
  text
    ? `${indent}/** ${text.replace(/\*\//g, '* /').replace(/\n/g, ' ')} */\n`
    : '';
const eventDetail = (e) =>
  e.type?.text?.match(/^CustomEvent<(.+)>$/)?.[1] ?? 'unknown';
// 'primary' | 'secondary' -> ['primary', 'secondary'] (null when not a string literal union)
const literals = (text) => {
  const parts = (text ?? '').split('|').map((p) => p.trim());
  return parts.length > 0 && parts.every((p) => /^'[^']*'$/.test(p))
    ? parts
    : null;
};

function prop(member) {
  const text = member.type?.text ?? 'unknown';
  const values = literals(text);
  const lines = [];
  if (text === 'boolean') {
    lines.push('type: Boolean', `default: ${member.default ?? 'false'}`);
  } else if (text === 'number') {
    lines.push('type: Number');
    if (member.default) lines.push(`default: ${member.default}`);
  } else {
    lines.push(`type: String as PropType<${text}>`);
    if (member.default) lines.push(`default: ${member.default}`);
    if (values)
      lines.push(
        `validator: (value: string) => [${values.join(', ')}].includes(value)`,
      );
  }
  return `${jsdoc(member.description, '    ')}    ${quote(member.name)}: {\n${lines.map((l) => `      ${l},`).join('\n')}\n    },`;
}

function component(el) {
  const name = el.name; // IuButton
  const members = (el.members ?? []).filter(
    (m) => m.kind === 'field' && m.attribute && !m.static && !m.readonly,
  );
  const events = el.events ?? [];
  const emits = events.map(
    (e) =>
      `${jsdoc(e.description, '    ')}    ${quote(e.name)}: (_event: CustomEvent<${eventDetail(e)}>) => true,`,
  );
  // iu-press -> onIuPress: Vue turns it back into an `iu-press` listener on the element.
  const listeners = events.map((e) => {
    const key = `on${e.name
      .split('-')
      .map((p) => p[0].toUpperCase() + p.slice(1))
      .join('')}`;
    return `          ${key}: (event: Event) => emit('${e.name}', event as CustomEvent<${eventDetail(e)}>),`;
  });
  const propNames = members.map((m) => `'${m.name}'`).join(', ');
  return `${jsdoc(el.summary ?? el.description, '')}export const ${name} = defineComponent({
  name: '${name}',
  props: {
${members.map(prop).join('\n')}
  },
${emits.length ? `  emits: {\n${emits.join('\n')}\n  },\n` : ''}  setup(props, { slots${events.length ? ', emit' : ''} }) {
    return () =>
      h(
        '${el.tagName}',
        {
          ...pick(props, [${propNames}]),${listeners.length ? `\n${listeners.join('\n')}` : ''}
        },
        slots.default?.(),
      );
  },
});`;
}

const header = `// Generated by scripts/generate.mjs from @intuition-ui/core/custom-elements.json.
// Do not edit by hand: run \`npm run generate -w @intuition-ui/vue\`.
`;

const file = `${header}import '@intuition-ui/core';
import { defineComponent, h, type PropType } from 'vue';

// Only defined values reach the element, so its own defaults still apply.
function pick<T extends object>(source: T, keys: (keyof T)[]): Partial<T> {
  const out: Partial<T> = {};
  for (const key of keys) {
    if (source[key] !== undefined) out[key] = source[key];
  }
  return out;
}

${elements.map(component).join('\n\n')}
`;

const out = 'src/components.generated.ts';
if (check) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== file) {
    console.error(
      `${out} is out of date. Run \`npm run generate -w @intuition-ui/vue\`.`,
    );
    process.exit(1);
  }
  console.log('Vue port is up to date.');
} else {
  writeFileSync(out, file);
  console.log(`Generated ${out} (${elements.length} element(s)).`);
}
