// Generates the React port from the Custom Elements Manifest of @intuition-ui/core.
//
//   src/components.generated.ts  React components (PascalCase) built with @lit/react
//   src/jsx.generated.ts         JSX types for using the custom element tags directly
//
// `--check` regenerates in memory and fails if the committed files are out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const manifestPath = require.resolve('@intuition-ui/core/custom-elements.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const check = process.argv.includes('--check');

const elements = manifest.modules.flatMap((m) =>
  (m.declarations ?? []).filter((d) => d.customElement && d.tagName),
);

// iu-press -> onIuPress
const reactEventProp = (name) =>
  `on${name
    .split('-')
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')}`;
// IuButton -> Button
const componentName = (className) => className.replace(/^Iu/, '');
const quote = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`);
const jsdoc = (text, indent) =>
  text
    ? `${indent}/** ${text.replace(/\*\//g, '* /').replace(/\n/g, ' ')} */\n`
    : '';
const eventDetail = (e) =>
  e.type?.text?.match(/^CustomEvent<(.+)>$/)?.[1] ?? 'unknown';

const header = `// Generated by scripts/generate.mjs from @intuition-ui/core/custom-elements.json.
// Do not edit by hand: run \`npm run generate -w @intuition-ui/react\`.
`;

function componentsFile() {
  const classes = elements.map((e) => e.name).join(', ');
  const blocks = elements.map((el) => {
    const events = (el.events ?? []).map(
      (e) =>
        `    ${reactEventProp(e.name)}: '${e.name}' as EventName<CustomEvent<${eventDetail(e)}>>,`,
    );
    const eventsBlock = events.length
      ? `\n  events: {\n${events.join('\n')}\n  },`
      : '';
    return `${jsdoc(el.summary ?? el.description, '')}export const ${componentName(el.name)} = createComponent({
  tagName: '${el.tagName}',
  elementClass: ${el.name},
  react: React,${eventsBlock}
  displayName: '${componentName(el.name)}',
});`;
  });
  const usesEvents = elements.some((el) => el.events?.length);
  return `${header}import { ${usesEvents ? 'type EventName, ' : ''}createComponent } from '@lit/react';
import { ${classes} } from '@intuition-ui/core';
import * as React from 'react';

${blocks.join('\n\n')}
`;
}

function jsxFile() {
  const classes = elements.map((e) => e.name).join(', ');
  const blocks = elements.map((el) => {
    const props = (el.members ?? [])
      .filter(
        (m) => m.kind === 'field' && m.attribute && !m.static && !m.readonly,
      )
      .map(
        (m) =>
          `${jsdoc(m.description, '        ')}        ${quote(m.name)}?: ${m.type?.text ?? 'unknown'};`,
      );
    const events = (el.events ?? []).map(
      (e) =>
        `${jsdoc(e.description, '        ')}        ${quote(`on${e.name}`)}?: (event: CustomEvent<${eventDetail(e)}>) => void;`,
    );
    return `      '${el.tagName}': ElementProps<${el.name}> & {\n${[...props, ...events].join('\n')}\n      };`;
  });
  return `${header}import type { ${classes} } from '@intuition-ui/core';
import type { DetailedHTMLProps, HTMLAttributes } from 'react';

type ElementProps<E> = DetailedHTMLProps<HTMLAttributes<E>, E>;

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${blocks.join('\n')}
    }
  }
}
`;
}

const outputs = {
  'src/components.generated.ts': componentsFile(),
  'src/jsx.generated.ts': jsxFile(),
};
let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== content) {
      console.error(
        `${file} is out of date. Run \`npm run generate -w @intuition-ui/react\`.`,
      );
      stale = true;
    }
  } else {
    writeFileSync(file, content);
  }
}
if (stale) process.exit(1);
console.log(
  check
    ? 'React port is up to date.'
    : `Generated ${Object.keys(outputs).join(', ')} (${elements.length} element(s)).`,
);
